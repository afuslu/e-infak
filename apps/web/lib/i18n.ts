export const RTL_LANGUAGES = new Set(['ar', 'fa', 'ur', 'he'])

export function isRtl(locale: string) {
  return RTL_LANGUAGES.has(locale)
}

export function translator(locale: string) {
  const dict = DICTIONARIES[locale] || DICTIONARIES.en
  return (key: MessageKey) => dict[key] || tr[key]
}

/** Locale on the client: the `lang` cookie set by the middleware. */
export function clientLocale(): string {
  if (typeof document === 'undefined') return 'tr'
  const value = document.cookie.split(';').map((c) => c.trim()).find((c) => c.startsWith('lang='))?.slice(5)
  return value && /^[a-z]{2}$/.test(value) ? value : 'tr'
}
